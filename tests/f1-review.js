import * as T from "three";
import { OrbitControls } from "three/addons/controls/OrbitControls.js";
import { landmarkModel } from "../src/models.js";
const scene = new T.Scene();
scene.background = new T.Color(0xfffaf0);
scene.add(new T.HemisphereLight(0xffffff, 0x8c8075, 2));
const sun = new T.DirectionalLight(0xffffff, 3);
sun.position.set(-3, 7, 5);
scene.add(sun);
const model = landmarkModel("f1");
scene.add(model);
const camera = new T.PerspectiveCamera(34, innerWidth / innerHeight, 0.1, 100);
camera.position.set(-6.4, 3.3, 6.9);
const renderer = new T.WebGLRenderer({ antialias: true });
renderer.setSize(innerWidth, innerHeight);
renderer.toneMapping = T.ACESFilmicToneMapping;
document.body.append(renderer.domElement);
const controls = new OrbitControls(camera, renderer.domElement);
controls.target.set(0, 0.6, 0);
controls.update();
renderer.setAnimationLoop(() => renderer.render(scene, camera));
window.modelReady = true;
